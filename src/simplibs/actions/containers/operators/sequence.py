from typing import Any
from simplibs.types import tuple_not_empty
# Outers
from ...decorator import to_action
from .._helpers import as_action


@to_action
def sequence(
    data: Any,
    steps: tuple_not_empty,
) -> Any:
    """Chains any number of steps left to right."""

    # 1. Initialize result with the incoming data
    result = data

    # 2. Sequentially process each step, feeding the result of one into the next
    for step in steps:
        result = as_action(step)(result)

    # 3. Return the final accumulated result
    return result


async def _sequence_acall(self, data: Any) -> Any:
    """Async counterpart of `sequence`'s own body.

    Awaits each step via its own `.acall(...)` rather than relying on
    `Action`'s default to-thread bridge over the whole synchronous loop
    — see this module's own design notes for why that distinction matters.
    """

    # 1. Initialize result with the incoming data
    result = data

    # 2. Sequentially await each step, feeding the result of one into the next
    for step in self.steps:
        result = await as_action(step).acall(result)

    # 3. Return the final accumulated result
    return result


# Attach the hand-written async counterpart directly onto the generated
# class — see design notes for why this can't be derived generically by
# create_action, the same way SequenceCompose.compose() can't be either.
sequence.acall = _sequence_acall

sequence = sequence
"""
Chains any number of steps left to right, threading the output of each
step into the next.

Init Params:
    steps (tuple_not_empty[Action | Rule | Callable[[Any], Any]]): The steps to
        run in order. Must contain at least one step.

Main Param:
    data (Any): The initial input fed to the first step.

Output:
    Any: The final step's return value.

For the self-flattening variant `Action.then`/`>>` actually builds under
the hood, see `SequenceCompose` in `compose_class/`. Callable both
synchronously (`sequence(steps=(...))(data)`) and asynchronously
(`await sequence(steps=(...)).acall(data)`) — each step resolves to
whichever calling convention fits it best.

Example:
    >>> sequence(steps=(strip, upper))("  hello  ")
    'HELLO'
"""


_DESIGN_NOTES = """
# sequence — n-ary sequential chaining

## Why a tuple parameter, not `*steps`
`create_action`'s `validate_param_kinds` rejects `VAR_POSITIONAL`
(`*args`) — a function with a variadic parameter cannot be wrapped by
`create_action`. `steps: tuple_not_empty` is the only compatible shape,
and it is meaningfully typeable (`IsTyping` handles `tuple` types
without trouble). Users still compose with `a >> b >> c` — this detail
only concerns the raw function's own call convention.

## Non-empty tuple contract via type annotation
Instead of manual `if not steps:` runtime checks inside the body, `sequence`
leverages `tuple_not_empty` from `simplibs.types`. Validation of empty step
tuples is delegated directly to the `@to_action` decorator layer.

## Relationship to SequenceCompose
This plain `sequence` container works correctly on its own but nests
when chained directly (`Sequence(steps=(a,)) >> b` would otherwise build
a `Sequence` holding another `Sequence` as one of its steps).
`SequenceCompose` (in `compose_class/`) is what `Action.then` actually
constructs, precisely to avoid that nesting. Construct `sequence`
directly only when you deliberately want a fixed, non-flattening group
of steps as a single unit.

## Why `acall` is hand-attached, not generated by `create_action`
`sequence`'s own source function is plain `def`, never `async def` — its
job is to run OTHER actions, not to itself be I/O-bound. `create_action`
therefore builds a synchronous `act`/`__call__` for it exactly as
before, and — left alone — `sequence` instances would inherit `Action`'s
default `acall`: `asyncio.to_thread(self.__call__, data)`. That default
would be actively wrong here for two reasons: (1) it would run the
ENTIRE loop inside one worker thread, so composing with `parallel`'s `&`
would never actually run concurrently even when awaited, and (2) the
very first step built from a genuinely `async def` source would
immediately hit that step's own raising synchronous `__call__` (an
async-sourced action's `__call__` is designed to raise — see
`create_call`'s design notes), because the default bridge calls
`self.__call__` on each child, not `self.acall`.

`_sequence_acall` fixes both: it iterates the SAME `steps`, but calls
each one's own `.acall(...)` — which resolves correctly whether that
step is natively async (no thread hop at all) or plain sync (gets
`Action`'s own to-thread bridge, applied per step, not for the whole
chain at once). Attaching it directly onto the generated class
(`sequence.acall = _sequence_acall`) rather than teaching `create_action`
to special-case this is the same choice already made for
`SequenceCompose.compose` — bespoke behavior specific to what THIS
container does with its children, not something a generic factory could
derive from `sequence`'s own signature.

## Why `SequenceCompose` needs no equivalent change of its own
`SequenceCompose` subclasses `sequence` and inherits `acall` through the
normal MRO, exactly the way it already inherits `act`/`__call__`/
`__init__`. `_sequence_acall` only ever reads `self.steps` — present on
both the plain container and the flattened `Compose` subclass alike —
so nothing about flattening (`compose()`) needs to know or care about
`acall` at all.
"""
