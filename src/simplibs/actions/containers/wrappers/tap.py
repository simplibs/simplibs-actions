from typing import Any
# Outers
from ...decorator import to_action
from .._helpers import as_action


@to_action
def tap(
    data: Any,
    action: Any,
) -> Any:
    """Runs `action` as a side effect, returns the ORIGINAL data unchanged."""

    # 1. Execute action as a side effect over data
    as_action(action)(data)

    # 2. Return original data unchanged
    return data


async def _tap_acall(self, data: Any) -> Any:
    """Async counterpart of `tap`'s own body.

    Awaits `action` via its own `.acall(...)` for the side effect, then
    returns the original `data` unchanged — identical semantics to the
    synchronous version, just async-aware for the side-effect call.
    """

    # 1. Await action as a side effect over data
    await as_action(self.action).acall(data)

    # 2. Return original data unchanged
    return data


# Attach the hand-written async counterpart directly onto the generated class —
# see design notes for why this can't be derived generically by create_action.
tap.acall = _tap_acall

tap = tap
"""
Runs `action` as a side effect over `data`, returns `data` unchanged.

Init Params:
    action (Action | Rule | Callable[[Any], Any]): Runs for its side
        effect; its return value is discarded.

Main Param:
    data (Any): The value observed by `action` and returned unchanged.

Output:
    Any: The same `data`, unchanged.

`data & action` (via `parallel`) would also run `action` alongside the
original data, but returns a tuple `(data, action_result)` — the caller
would have to pick the first element to get a clean "side effect, data
unchanged" behavior. `tap` does this directly, as a named, readable
intent. Callable both synchronously (`tap(action=...)(data)`) and
asynchronously (`await tap(action=...).acall(data)`) — useful for a side
effect that is itself I/O-bound (e.g. writing a log line to a file)
without blocking the surrounding pipeline's event loop.

Example:
    >>> tap(action=log_to_file)(record)
"""


_DESIGN_NOTES = """
# tap — side effect without affecting data

## Why `tap`, not composing from `parallel`
`data & action` would also run `action` alongside the original data but
returns `(data, action_result)` — the caller must pick the first element
to get "side effect, data unchanged" behavior. `tap` does this directly
as a named, readable intent rather than a derivation from a more general
tool.

## Why `acall` is hand-attached, not generated by `create_action`
`tap`'s own source function is plain `def` — its job is to run ANOTHER
action for its side effect, not to itself be I/O-bound. Left alone,
`tap` instances would inherit `Action`'s default `acall`, which would
call `action`'s synchronous `__call__` — breaking immediately if
`action` happens to be built from an `async def` source (its `__call__`
is designed to raise; see `create_call`'s design notes). `_tap_acall`
mirrors the sync body exactly, substituting `await ...acall(...)` for
the direct side-effect call, and still discards its result and returns
the original `data` unchanged, same as before.
"""
